'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs'); const path = require('node:path');
const { randomUUID, randomBytes } = require('node:crypto');
const { chromium, request } = require('playwright');
if (process.env.E2E_DISPOSABLE !== 'true' || !process.env.E2E_ENV_FILE?.includes('release-demo')) throw new Error('Use isolated release wrapper');
const directory = path.resolve(__dirname, '../../.local/release-demo');
const accounts = JSON.parse(fs.readFileSync(path.join(directory, 'accounts.json')));
const admin = accounts.find(a => a.id === 'demo-release-admin');
const web = 'http://localhost:3000', api = 'http://localhost:4000';
const output = path.join(directory, 'evidence'); fs.mkdirSync(output, { recursive: true });
const mutate = async (client, route, data, method = 'POST') => {
  const csrf = await (await client.get(api + '/auth/csrf')).json();
  return client.fetch(api + route, { method, data, headers: { Origin: web, 'X-CSRF-Token': csrf.csrfToken } });
};
(async () => {
  const browser = await chromium.launch({ headless: true, executablePath: process.env.E2E_CHROME_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe' });
  const student = await request.newContext();
  try {
    const name = 'Әсел Ғалымқызы Қанат Нұрсұлтанқызы Өмірбекова';
    const registered = await mutate(student, '/auth/register', { name, email: `certificate-${randomUUID()}@example.invalid`, password: `Demo!!99${randomBytes(16).toString('hex')}` });
    assert.equal(registered.status(), 201); const user = (await registered.json()).user;
    const context = await browser.newContext(); const page = await context.newPage();
    await page.goto(web + '/auth/login'); await page.getByLabel('Email', { exact: true }).fill(admin.email);
    await page.getByLabel('Пароль', { exact: true }).fill(admin.password); await page.locator('button[type=submit]').click(); await page.waitForURL('**/dashboard');
    const granted = await mutate(context.request, `/admin/users/${user.id}/grant-certificate/demo-release-web-foundations-v1`, {});
    assert.equal(granted.status(), 201); const cert = (await granted.json()).certificate;
    assert.equal(cert.issuedVia, 'ADMIN_OVERRIDE'); assert.equal(cert.recipientName, name);
    assert.equal((await mutate(student, '/users/me/profile', { name: 'Changed live profile' }, 'PATCH')).status(), 200);
    const verifier = await browser.newPage({ viewport: { width: 390, height: 844 } });
    const url = `${web}/verify/${cert.qrCode}`;
    await verifier.goto(url); await verifier.getByText('Сертификаттың берілгені расталды', { exact: true }).waitFor();
    await verifier.getByText(name, { exact: true }).waitFor();
    const verifyResponse = await fetch(`${api}/certificates/verify/${cert.qrCode}`);
    assert.match(verifyResponse.headers.get('cache-control'), /no-store/);
    assert.doesNotMatch(JSON.stringify(await verifyResponse.json()), /@example|Changed live profile|revocationReason|reviewReason|recordings\//);
    await verifier.screenshot({ path: path.join(output, 'verify-valid.png'), fullPage: true });
    const pdf = await student.get(`${api}/certificates/${cert.id}/pdf`); assert.equal(pdf.status(), 200); assert.match(pdf.headers()['content-type'], /application\/pdf/);
    fs.writeFileSync(path.join(output, 'issued-certificate.pdf'), await pdf.body());
    const anonymous = await request.newContext();
    assert.equal((await anonymous.get(`${api}/certificates/${cert.id}/pdf`)).status(), 401); await anonymous.dispose();
    assert.equal((await student.get(`${api}/admin/users/${user.id}/certificates`)).status(), 403);
    assert.equal((await mutate(student, `/admin/certificates/${cert.id}/revoke`, { reason: 'Denied student action' })).status(), 403);
    await page.route(`${api}/courses`, route => route.fulfill({ status: 503, json: { error: 'Catalog retry fixture' } }));
    await page.goto(`${web}/dashboard/admin/users/${user.id}`);
    await page.getByRole('button', { name: 'Қайта жүктеу', exact: true }).waitFor();
    await page.unroute(`${api}/courses`);
    const catalogRetry = page.waitForResponse(r => r.url() === `${api}/courses` && r.status() === 200);
    await page.getByRole('button', { name: 'Қайта жүктеу', exact: true }).click();
    await catalogRetry;
    await page.getByText('Сертификатты кері қайтару', { exact: true }).click();
    await page.getByLabel('Кері қайтару себебі', { exact: true }).fill('Fictional release acceptance: permanent revocation demonstration');
    const revoked = page.waitForResponse(r => r.url().endsWith(`/certificates/${cert.id}/revoke`) && r.request().method() === 'POST');
    await page.getByRole('button', { name: 'Кері қайтаруды растау', exact: true }).click(); assert.equal((await revoked).status(), 201);
    await page.getByText(/Күші жойылған/).first().waitFor();
    await verifier.reload(); await verifier.getByText('Сертификаттың күші жойылған', { exact: true }).waitFor();
    await verifier.screenshot({ path: path.join(output, 'verify-revoked.png'), fullPage: true });
    assert.equal((await mutate(context.request, `/admin/users/${user.id}/grant-certificate/demo-release-web-foundations-v1`, {})).status(), 409);
    await verifier.goto(`${web}/verify/${randomUUID()}`); await verifier.getByText('Сертификат табылмады', { exact: true }).waitFor();
    await verifier.screenshot({ path: path.join(output, 'verify-not-found.png'), fullPage: true });
    await verifier.route('**/certificates/verify/**', route => route.fulfill({ status: 503, json: { error: 'Acceptance outage fixture' } }));
    await verifier.goto(url); await verifier.getByRole('button', { name: 'Қайта тексеру' }).waitFor();
    await verifier.screenshot({ path: path.join(output, 'verify-unavailable-fixture.png'), fullPage: true });
    await verifier.unrouteAll(); await verifier.getByRole('button', { name: 'Қайта тексеру' }).click();
    await verifier.getByText('Сертификаттың күші жойылған', { exact: true }).waitFor();
    fs.writeFileSync(path.join(output, 'certificate-acceptance.json'), JSON.stringify({ status: 'PASS', at: new Date().toISOString(), userId: user.id, certificateId: cert.id, verificationUrl: url,
      checks: ['admin override separately labelled', 'snapshot after profile rename', 'owner PDF', 'foreign/anonymous access denied', 'admin catalog failure and complete retry', 'browser admin revocation', 'same URL rescan revoked', 'reissue denied', 'unknown state', '503 fixture unavailable and retry'], physicalPhone: 'NOT_RUN' }, null, 2));
    console.log('PASS certificate: actual issuance/PDF/snapshot, admin UI revoke, anonymous rescan, all4 verifier states; outage UI uses503 fixture');
  } finally { await student.dispose(); await browser.close(); }
})().catch(error => { console.error(`Certificate acceptance failed: ${error.name}: ${error.message.replace(/[a-f0-9]{64}/g, '[redacted]')}`); process.exitCode = 1; });
